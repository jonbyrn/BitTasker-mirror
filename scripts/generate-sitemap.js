#!/usr/bin/env node

import fs from 'fs';
import path from 'path';

const domain = 'https://bittasker.com';
const buildDir = 'build';

// Ensure build directory exists
if (!fs.existsSync(buildDir)) {
	fs.mkdirSync(buildDir, { recursive: true });
}

// Define the URLs manually for better control
const urls = [
	// Home page
	'/',
	// Company pages
	'/about',
	'/careers',
	'/tasker-fees',
	'/community-guidelines',
	'/contact',
	'/faq',
	'/how-it-works',
	'/press',
	'/privacy',
	'/security',
	'/taskee-fees',
	'/tasker-principles',
	'/terms',
	// Auth pages
	'/auth/login',
	'/auth/signup',
	'/auth/recover',
	'/verify-email'
];

// Generate sitemap XML manually
const sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <!-- This file was automatically generated by svelte-sitemap integration -->
${urls.map(url => `  <url>
    <loc>${domain}${url}</loc>
    <changefreq>weekly</changefreq>
    <priority>0.7</priority>
  </url>`).join('\n')}
</urlset>`;

// Write ONLY to build directory (not static)
fs.writeFileSync(path.join(buildDir, 'sitemap.xml'), sitemapXml);

console.log('✅ Sitemap generated successfully!');
console.log(`📁 Generated file: ${buildDir}/sitemap.xml`);
console.log(`📋 URLs included: ${urls.length}`);
console.log('💡 Note: sitemap.xml is now served dynamically from /sitemap.xml route'); 