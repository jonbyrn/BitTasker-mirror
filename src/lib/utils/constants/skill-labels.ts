const SKILL_CANONICAL = new Map(
	Object.entries(SKILL_ES).map(([english, spanish]) => [spanish, english])
);

export function skillLabel(skill: string, language: string): string {
	if (!String(language).startsWith('es')) return skill;
	return SKILL_ES[skill] || skill;
}

/** Map a displayed skill back to the English string saved on the listing. */
export function canonicalSkill(skill: string): string {
	return SKILL_CANONICAL.get(skill) || skill;
}

export function skillHasSpanishLabel(skill: string): boolean {
	return Object.prototype.hasOwnProperty.call(SKILL_ES, skill);
}
